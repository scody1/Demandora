import os
import json
import logging
import requests

logger = logging.getLogger(__name__)

# Default prompt rules
LLM_SYSTEM_PROMPT = """You are an advanced Supply Chain & Demand Planning AI assistant.
Your exclusive purpose is to EXPLAIN the provided numerical forecast results generated by the statistical and machine learning backend.

ABSOLUTE RULES:
1. EXPLAIN ONLY. You are strictly forbidden from calculating, generating, or modifying forecast quantities, confidence intervals, prediction intervals, WAPE, stock, or net requirements.
2. Use ONLY the supplied numerical/business facts in the payload. Do not invent missing values.
3. Never invent historical events, customer information, project information, seasonality patterns, or model performance metrics.
4. Never change the supplied numbers.
5. If requested information is unavailable, explicitly state that it is unavailable.
6. Do not offer alternative forecast quantities or suggest overriding the ML model output.

Output MUST be valid JSON conforming to the following structure:
{
  "summary": "A 1-2 sentence high-level summary of the demand outlook.",
  "drivers": [
    "Driver 1 (e.g. recent demand acceleration)",
    "Driver 2 (e.g. stable seasonal pattern)"
  ],
  "risk": "Assessment of forecast reliability and error margins.",
  "plannerAttention": "Actionable advice based strictly on stock, open PO, and net requirement.",
  "recommendation": "Final summary recommendation for the planner."
}
"""

def generate_explanation(payload: dict) -> dict:
    """
    Calls an LLM API to generate an explanation of the forecast payload.
    If no API key is configured or the service fails, returns a fallback explanation state.
    """
    api_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("OPENAI_API_KEY")
    
    # Graceful degradation if no LLM API key exists.
    if not api_key:
        return {
            "unavailable": True,
            "reason": "AI explanations are unavailable. Your numerical forecast is still fully operational."
        }

    # Format the payload for the prompt
    user_prompt = f"Explain the following numerical forecast result strictly adhering to your system rules:\n\n{json.dumps(payload, indent=2)}"

    try:
        if os.environ.get("GEMINI_API_KEY"):
            url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={api_key}"
            headers = {'Content-Type': 'application/json'}
            data = {
                "system_instruction": {
                    "parts": [{"text": LLM_SYSTEM_PROMPT}]
                },
                "contents": [
                    {
                        "parts": [{"text": user_prompt}]
                    }
                ],
                "generationConfig": {
                    "response_mime_type": "application/json"
                }
            }
            response = requests.post(url, headers=headers, json=data, timeout=10)
            response.raise_for_status()
            
            resp_json = response.json()
            try:
                text = resp_json['candidates'][0]['content']['parts'][0]['text']
                raw_json = json.loads(text)
                from backend.main import ExplanationResponse
                # Validate and strip extra fields
                validated = ExplanationResponse(**raw_json)
                return validated.model_dump()
            except (KeyError, IndexError, json.JSONDecodeError) as e:
                logger.error(f"Failed to parse Gemini response: {e}")
                return {
                    "unavailable": True,
                    "reason": "AI response could not be validated. Numerical forecast is unaffected."
                }
            except Exception as e:
                logger.error(f"Validation error in Gemini response: {e}")
                return {
                    "unavailable": True,
                    "reason": "AI response could not be validated. Numerical forecast is unaffected."
                }

                
        elif os.environ.get("OPENAI_API_KEY"):
            url = "https://api.openai.com/v1/chat/completions"
            headers = {
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json"
            }
            data = {
                "model": "gpt-4o-mini",
                "messages": [
                    {"role": "system", "content": LLM_SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt}
                ],
                "response_format": {"type": "json_object"}
            }
            
            response = requests.post(url, headers=headers, json=data, timeout=10)
            response.raise_for_status()
            
            resp_json = response.json()
            try:
                content = resp_json['choices'][0]['message']['content']
                raw_json = json.loads(content)
                from backend.main import ExplanationResponse
                validated = ExplanationResponse(**raw_json)
                return validated.model_dump()
            except (KeyError, IndexError, json.JSONDecodeError) as e:
                logger.error(f"Failed to parse OpenAI response: {e}")
                return {
                    "unavailable": True,
                    "reason": "AI response could not be validated. Numerical forecast is unaffected."
                }
            except Exception as e:
                logger.error(f"Validation error in OpenAI response: {e}")
                return {
                    "unavailable": True,
                    "reason": "AI response could not be validated. Numerical forecast is unaffected."
                }

    except Exception as e:
        logger.error(f"LLM Provider API Error: {str(e)}")
        return {
            "unavailable": True,
            "reason": "AI service unavailable. Numerical forecast is unaffected."
        }
